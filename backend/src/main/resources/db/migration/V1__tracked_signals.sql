-- Every recommended setup, followed as a paper trade.
CREATE TABLE tracked_signal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    style           VARCHAR(16)      NOT NULL,
    symbol          VARCHAR(32)      NOT NULL,
    signal_date     DATE             NOT NULL,
    score           INTEGER          NOT NULL,
    classification  VARCHAR(20)      NOT NULL,
    confidence      VARCHAR(10)      NOT NULL,
    entry_price     DOUBLE PRECISION NOT NULL,
    stop_price      DOUBLE PRECISION NOT NULL,
    target_price    DOUBLE PRECISION NOT NULL,
    status          VARCHAR(16)      NOT NULL,
    exit_date       DATE,
    exit_price      DOUBLE PRECISION,
    return_pct      DOUBLE PRECISION,
    max_gain_pct    DOUBLE PRECISION NOT NULL,
    max_loss_pct    DOUBLE PRECISION NOT NULL,
    sessions_held   INTEGER          NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_tracked_signal UNIQUE (style, symbol, signal_date)
);

CREATE INDEX ix_tracked_signal_status ON tracked_signal (status);
