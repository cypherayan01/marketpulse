-- Every prediction (buy setups and stocks to avoid) and how it turned out vs Nifty at fixed checkpoints.
-- r_N = stock % change N sessions after the signal, n_N = Nifty over the same dates. LIVE = from scheduled
-- scans, REPLAY = reconstructed from history (an estimate).
CREATE TABLE prediction (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source          VARCHAR(8)       NOT NULL,
    style           VARCHAR(16)      NOT NULL,
    symbol          VARCHAR(32)      NOT NULL,
    segment         VARCHAR(16),
    signal_date     DATE             NOT NULL,
    score           INTEGER          NOT NULL,
    classification  VARCHAR(20)      NOT NULL,
    call_type       VARCHAR(8)       NOT NULL,
    price           DOUBLE PRECISION NOT NULL,
    nifty_price     DOUBLE PRECISION NOT NULL,
    news_sentiment  INTEGER          NOT NULL,
    r_1             DOUBLE PRECISION,
    r_2             DOUBLE PRECISION,
    r_3             DOUBLE PRECISION,
    r_5             DOUBLE PRECISION,
    r_10             DOUBLE PRECISION,
    r_20             DOUBLE PRECISION,
    r_40             DOUBLE PRECISION,
    r_60             DOUBLE PRECISION,
    n_1             DOUBLE PRECISION,
    n_2             DOUBLE PRECISION,
    n_3             DOUBLE PRECISION,
    n_5             DOUBLE PRECISION,
    n_10             DOUBLE PRECISION,
    n_20             DOUBLE PRECISION,
    n_40             DOUBLE PRECISION,
    n_60             DOUBLE PRECISION,
    next_open_pct   DOUBLE PRECISION,
    next_high_pct   DOUBLE PRECISION,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_prediction UNIQUE (source, style, symbol, signal_date, call_type)
);

CREATE INDEX ix_prediction_source_date ON prediction (source, signal_date);
